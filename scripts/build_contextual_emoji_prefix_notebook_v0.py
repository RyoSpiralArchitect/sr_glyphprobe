#!/usr/bin/env python3
"""Generate and execute a bilingual, model-free diagnostic receipt notebook."""
from __future__ import annotations

import argparse
import hashlib
import importlib.metadata
import json
from pathlib import Path
import textwrap

import nbformat
from nbclient import NotebookClient


def build(root, report_path):
    report_relative = report_path.resolve().relative_to(root.resolve()).as_posix()
    report = json.loads(report_path.read_text())
    pin = hashlib.sha256(report_path.read_bytes()).hexdigest()
    cells = []
    def md(value):
        cells.append(nbformat.v4.new_markdown_cell(textwrap.dedent(value).strip()))
    def code(value):
        cells.append(nbformat.v4.new_code_cell(textwrap.dedent(value).strip()))
    md("""
    # Shared-prefix numerical consistency / 共通接頭列の数値整合性

    ## tl;dr

    Eight previously observed input pairs; at most 56 engineering forwards.
    This notebook verifies saved receipts using CPU-only Python. It makes no
    model, tokenizer, GPU, or network calls, and adds no scientific observations.
    既存の8入力組を使う最大56回の実装診断。ここでは記録だけをCPUで検算する。
    新しい科学的標本・修正済みの課題判定・因果同定として数えない。

    [Protocol / English](../docs/CONTEXTUAL_EMOJI_PREFIX_CONSISTENCY_V0.md) ·
    [実行前の仕様 / 日本語](../docs/CONTEXTUAL_EMOJI_PREFIX_CONSISTENCY_V0.ja.md)
    """)
    md("""
    ## Context & methods / 問いと方法

    The panel was selected from known residuals and length controls. It is a
    diagnostic, not a prevalence sample. Original A/B calls and their repeats
    must reproduce historical scores exactly. Padded calls share both model and
    FP32 normalization shapes. Prefix-only calls use a different shape and are
    descriptive comparisons, not an oracle. Resource checks are separate gates.
    既知の差と長さ対照から選んだパネルであり、出現率を推定しない。元の採点の
    完全再現、反復一致、形状をそろえた接頭列の一致を別々に検証する。
    独立接頭列の採点を正解とは仮定しない。資源境界も個別に照合する。

    ### Key assumptions / 前提

    Matching saved digests record the runner's tensor-equality observation;
    raw logits are not archived or regenerated by this notebook.
    Monitoring cannot rule out activity between observations. Full candidate
    score changes are descriptive. Single input pairs cannot recompute a block's
    H, crossover, or four-condition alignment. Human task validation remains open.
    logits本体は保存していない。監視の間の負荷は不明。入力1組から課題全体の
    判定は更新できず、人による課題妥当性の検証も未実施である。
    """)
    md("## Data / 記録の照合")
    code(f"""
    from pathlib import Path
    import hashlib, importlib.util, json
    root = next(p for p in [Path.cwd(), *Path.cwd().parents]
                if (p / "scripts/validate_contextual_emoji_prefix_consistency_v0.py").is_file())
    report_path = root / {report_relative!r}
    assert hashlib.sha256(report_path.read_bytes()).hexdigest() == {pin!r}
    report = json.loads(report_path.read_text())
    checker = root / "scripts/validate_contextual_emoji_prefix_consistency_v0.py"
    assert hashlib.sha256(checker.read_bytes()).hexdigest() == report["provenance"]["checker_sha256"]
    module_spec = importlib.util.spec_from_file_location("independent_prefix_checker", checker)
    validation = importlib.util.module_from_spec(module_spec)
    module_spec.loader.exec_module(validation)
    base = report_path.parent
    rebuilt = validation.analyze(base / "specification.json", base / "run56", root)
    # Absolute provenance paths can differ when replaying a copied repository.
    # All hashes and scientific/resource fields must remain identical.
    for value in (rebuilt, report):
        value["provenance"]["checker_path"] = checker.name
        for key in ("specification", "run_completed"):
            value["provenance"][key]["path"] = Path(value["provenance"][key]["path"]).name
    assert rebuilt == report
    print("Independent raw/spec/runtime/resource receipt replay: PASS")
    """)
    md("## Results / 各境界の結果")
    code("""
    for key in ("status", "planned_inputs", "planned_forward_attempts",
                "actual_forward_attempts", "completed_forward_scores",
                "full_runtime_identity_matches_historical", "numerical_gate_passed",
                "bounded_numerical_gate_passed", "new_scientific_n", "block_H_recomputed"):
        print(key, report[key])
    print("Resource validation:", json.dumps(report["resource_validation"], indent=2))
    assert report["actual_forward_attempts"] <= 56
    assert report["new_scientific_n"] == 0 and report["block_H_recomputed"] is False
    """)
    code("""
    for row in report["input_summary"]:
        print(json.dumps(row, ensure_ascii=False, sort_keys=True))
    assert len(report["input_summary"]) == 8
    """)
    md("""
    ## Risks & limitations / 解釈の上限

    A failed gate remains failed. Passing this panel would qualify a scoring
    geometry for broader validation; it would not repair the full development
    grid. A complete versioned reassessment is required before paper numbers
    change. No precision sweep or sample expansion follows automatically.
    不一致があればそのまま記録する。通過しても全開発データの修復を意味しない。
    論文数値の更新には別版として全対象を再評価する必要がある。追加実験は自動起動しない。

    ## Next decisions / 次の判断

    Read the paired result note for observed outcomes and the narrowly justified
    next diagnostic. Human interpretation, independent scenarios, and natural-state
    causal tests remain separate later stages.
    観測結果と次の最小診断は結果ノートを参照。人による意味検証、新課題、自然状態の
    因果検査は、それぞれ独立した後続段階として保持する。
    """)
    notebook = nbformat.v4.new_notebook(cells=cells)
    notebook.metadata.update(
        kernelspec={"display_name": "Python 3", "language": "python", "name": "python3"},
        glyphprobe={"report_sha256": pin, "report_status": report["status"],
                    "model_forwards": 0, "tokenizer_calls": 0, "network_calls": 0,
                    "presentation_dependencies": {k: importlib.metadata.version(k)
                        for k in ("nbformat", "nbclient", "ipykernel")}})
    return notebook


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, required=True)
    parser.add_argument("--report", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    if args.output.exists():
        raise FileExistsError("Refusing to overwrite notebook")
    notebook = build(args.root, args.report)
    NotebookClient(notebook, timeout=120, kernel_name="python3",
                   resources={"metadata": {"path": str(args.root.resolve())}}).execute()
    nbformat.validate(notebook)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    with args.output.open("x", encoding="utf-8") as handle:
        nbformat.write(notebook, handle)
    print(json.dumps({"notebook": str(args.output), "executed_code_cells":
                      sum(c.cell_type == "code" for c in notebook.cells),
                      "sha256": hashlib.sha256(args.output.read_bytes()).hexdigest()}))


if __name__ == "__main__":
    main()
